"""M2.5 — Preview widget.

Displays a sample paragraph using the *preview* font generated by O1's
`build_preview()`. Because the font is not installed system-wide, we have
to load it into a temporary `Pango.FontMap` and use that just for this widget.
"""

from __future__ import annotations

import gi

gi.require_version("Gtk", "4.0")
gi.require_version("Pango", "1.0")

from gi.repository import Gtk, Pango  # noqa: E402

from scribesense.contracts.fonts import PreviewFonts  # noqa: E402


SAMPLE_TEXT = (
    "Reading is easier when letters have room to breathe. Some readers need "
    "more space between words, others need more space between lines, and the "
    "right amount differs from person to person. ScribeSense lets each reader "
    "choose, then applies that choice everywhere they read."
)


class PreviewWidget(Gtk.Box):
    """A label that renders the sample text in the generated preview font."""

    def __init__(self) -> None:
        super().__init__(orientation=Gtk.Orientation.VERTICAL, spacing=12)

        self.label = Gtk.Label()
        self.label.set_wrap(True)
        self.label.set_max_width_chars(60)
        self.label.set_justify(Gtk.Justification.CENTER)
        # Fallback accessible label in case the font fails to load
        self.label.update_property(
            [Gtk.AccessibleProperty.LABEL], ["Font preview sample text"]
        )
        self.append(self.label)

        self._font_map: Pango.FontMap | None = None

    def update_preview(self, preview_fonts: PreviewFonts) -> None:
        """Load the preview font and apply it to the label."""
        # In a real GTK4 environment, we use a private FontMap and add the
        # font file via PangoFc or similar. Because PyGObject does not expose
        # a stable private font loading API across all versions, we use
        # `Gtk.Label.set_markup` with a span to set the family.
        # The preview font is loaded into the process by build_preview(),
        # so it is already resolvable by name if we set the correct family.
        
        self.label.set_text(SAMPLE_TEXT)
        
        # Set the font family and line height. We use Pango attributes to
        # bypass the theme's default font.
        attr_list = Pango.AttrList()
        attr_list.insert(Pango.attr_family_new(preview_fonts.reading_family))
        
        # Note: Pango does not directly support line-height in AttrList,
        # so the line height is provided by the font metrics (which O1's
        # patcher already modified).
        self.label.set_attributes(attr_list)

    def show_error(self, message: str) -> None:
        """If preview generation fails, show the error text instead of a broken font."""
        self.label.set_text(f"Preview unavailable: {message}")
        self.label.set_attributes(None)