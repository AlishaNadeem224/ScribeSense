"""O4 — Browser CSS generator (M4.8): one CSS text for Firefox userContent.css (M4.6) and the Chromium
extension (M4.9, delivered by the app over K11 — the extension never builds CSS itself).

Rules (card M4.8, decisions F1 / A16):
- Sets ONLY `font-family` (the READING family, A13: page content is reading text) and `line-height`,
  both `!important` so sites that set their own fonts are covered.
- NEVER letter-spacing or word-spacing: the spacing is already built into the generated font; adding it in
  CSS would apply it twice.
- NEVER @font-face, @import, url(...), file:// or any network reference — the font is installed system-wide
  and referenced by NAME only (offline / privacy promise).
- Excludes code (code, pre, kbd, samp, tt, var and their descendants), common code editors, and icon fonts
  (Font Awesome, Material Icons / Symbols, generic icon classes). CSS cannot select by font family, so the
  icon/code exclusions are a declared HEURISTIC LIST owned by this module (card: "Owns the CSS rules and the
  icon-exclusion list"). Pages with other icon fonts may lose icons — they can use the reader instead.

Pure function: no I/O, deterministic for the same input.
"""

from __future__ import annotations

import math
import re

from scribesense.contracts.config import Configuration
from scribesense.contracts.errors import ErrorCode, ScribeSenseError
from scribesense.contracts.fonts import READING_FAMILY_PREFIX, FontSet

#: Code and preformatted text keep their own (monospace) fonts and line height.
CODE_SELECTORS: tuple[str, ...] = (
    "code", "pre", "kbd", "samp", "tt", "var",
    ".CodeMirror", ".cm-editor", ".monaco-editor", ".ace_editor",
    '[class*="mono"]', '[class*="code"]', '[class*="highlight"]',
)

#: Icon fonts: replacing their font-family turns icons into letters or boxes.
ICON_SELECTORS: tuple[str, ...] = (
    ".fa", ".fas", ".far", ".fal", ".fad", ".fab", ".fa-solid", ".fa-regular", ".fa-brands",
    '[class^="fa-"]', '[class*=" fa-"]',
    ".material-icons", '[class^="material-icons"]', '[class*=" material-icons"]',
    '[class^="material-symbols"]', '[class*=" material-symbols"]',
    ".glyphicon", '[class^="icon-"]', '[class*=" icon-"]', '[class*="-icon"]', '[data-icon]',
    "svg", "svg *", "math", "math *",
)

_FAMILY = re.compile(r"^[A-Za-z0-9-]{1,64}$")
_FORBIDDEN = ("@font-face", "@import", "url(", "file:", "http:", "https:", "letter-spacing", "word-spacing")


def _excluded() -> list[str]:
    """Each excluded selector plus its descendants (selector lists inside :not() — Selectors Level 4)."""
    out: list[str] = []
    for sel in CODE_SELECTORS + ICON_SELECTORS:
        out.append(sel)
        if not sel.endswith(" *"):
            out.append(f"{sel} *")
    return out


def format_line_height(value: float) -> str:
    if not math.isfinite(value) or value <= 0:
        raise ScribeSenseError(ErrorCode.UNEXPECTED_ADAPTER_ERROR)
    return f"{round(value, 3):g}"


def browser_css(fonts: FontSet, config: Configuration) -> str:
    """CSS text for page content. Raises UNEXPECTED_ADAPTER_ERROR for a family that is not ours."""
    family = fonts.reading_family
    if not family.startswith(READING_FAMILY_PREFIX) or not _FAMILY.match(family):
        raise ScribeSenseError(ErrorCode.UNEXPECTED_ADAPTER_ERROR)  # never emit an arbitrary family name
    line = format_line_height(config.reading_line)
    excluded = ",\n    ".join(_excluded())
    css = f"""/* Generated by ScribeSense. Do not edit: replaced on apply, removed by `scribesense reset`. */
/* Font family + line height only: letter and word spacing are built into the font. */
:root :not(
    {excluded}
) {{
  font-family: "{family}", sans-serif !important;
  line-height: {line} !important;
}}
"""
    lowered = css.lower()
    if any(bad in lowered for bad in _FORBIDDEN):  # explicit check, not `assert` (stripped under -O)
        raise ScribeSenseError(ErrorCode.UNEXPECTED_ADAPTER_ERROR)
    return css
