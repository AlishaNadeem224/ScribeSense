class ScribeSenseError(Exception):
    """The only error type modules raise for expected failures (K3 rule 5, K8).

    Carries a code only — never a message with paths, text or other content.
    """

    def __init__(self, code: ErrorCode) -> None:
        super().__init__(code.value)
        self.code = code
