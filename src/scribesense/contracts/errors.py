"""K8 — Error codes (owner O3). ErrorCode list v1, approved 2026-10-09, ADD-ONLY.

Codes may be added (PR with owner + one other); existing codes are never renamed or reused.
Codes are fixed identifiers: never put paths, document text or exception messages in them.
K1 validation codes (NON_FINITE, OUT_OF_RANGE, ...) are Issue codes — see contracts.config.
"""

